from pydantic import BaseModel, Field
from typing import List


class ClassificationEvaluation(BaseModel):
    """
    Evaluation metrics for the Classification node
    for a SINGLE evaluation data point.
    """

    expected_query_type: str = Field(
        default="", description="The expected query type label for the user query."
    )

    predicted_query_type: str = Field(
        default="", description="The query type predicted by the classification node."
    )

    is_query_type_correct: bool = Field(
        default=False,
        description="True if predicted_query_type matches expected_query_type.",
    )

    expected_requires_clarification: bool = Field(
        default=False,
        description="Ground truth label indicating whether clarification is required.",
    )

    predicted_requires_clarification: bool = Field(
        default=False,
        description="The clarification-needed prediction generated by the system.",
    )

    is_clarification_prediction_correct: bool = Field(
        default=False,
        description="True if clarification prediction matches expected value.",
    )


class ClarificationEvaluation(BaseModel):
    """
    Evaluation metrics for the Clarification node
    for a SINGLE evaluation data point.
    """

    evaluation_needed: bool = Field(
        default=True,
        description="Ground truth indicating whether clarification evaluation was needed.",
    )

    evaluation_score: float = Field(
        default=0.0,
        ge=0.0,
        le=10.0,
        description=(
            "Overall quality score of the clarification response. "
            "Range: [0,10]. "
            "Higher scores indicate that the clarification response was clear, minimal, relevant, "
            "safe, and aligned with the clarification reason."
        ),
    )

    evaluation_reasoning: str = Field(
        default="",
        description=(
            "Detailed reasoning explaining the assigned evaluation score. "
            "Must discuss strengths and weaknesses of the clarification response, "
            "including whether it was necessary, focused, natural, concise, and aligned "
            "with the user's request and clarification reason."
        ),
    )


class PlanningEvaluation(BaseModel):
    """
    Evaluation metrics for the Planning node
    for a SINGLE evaluation data point.
    """

    generated_steps_count: int = Field(
        default=0, description="Number of tasks/steps generated by the planner."
    )

    correctly_generated_steps_count: int = Field(
        default=0,
        description="Number of generated steps that are correct and fulfil user's request",
    )

    step_correctness_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Step correctness score. "
            "Computed as correctly_generated_steps_count / generated_steps_count. "
            "Range: [0,1]."
        ),
    )

    num_required_steps: int = Field(
        default=0,
        description="Number of tasks/steps required to complete the user's request.",
    )

    num_fulfilling_steps: int = Field(
        default=0,
        description="Number of generated steps that actually fulfill the user's request according to the ground truth plan.",
    )

    step_completion_coverage_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Measures how well the generated plan covers the necessary steps to fulfill the user's request. "
            "Computed as num_fulfilling_steps / num_required_steps. "
            "Range: [0,1]."
        ),
    )

    is_step_ordering_correct: bool = Field(
        default=False,
        description=(
            "True if the generated steps are ordered correctly "
            "according to dependencies and execution flow."
        ),
    )

    total_generated_dependency_steps: int = Field(
        default=0,
        description="Total number of generated steps that have dependencies on other steps.",
    )

    correctly_generated_dependency_steps: int = Field(
        default=0,
        description="Number of correctly generated steps that have dependencies on other steps.",
    )

    dependency_accuracy_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Dependency accuracy score. "
            "Computed as correctly_generated_dependency_steps / total_generated_dependency_steps. "
            "Range: [0,1]."
        ),
    )

    generated_information_steps_count: int = Field(
        default=0, description="Number of information steps generated by the planner."
    )

    correctly_generated_information_steps_count: int = Field(
        default=0, description="Number of information steps generated correctly."
    )

    generated_command_steps_count: int = Field(
        default=0, ge=0, description="Number of command steps generated by the planner."
    )

    correctly_generated_command_steps_count: int = Field(
        default=0, description="Number of command steps generated correctly."
    )

    step_type_accuracy_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Step type accuracy score. "
            "Computed as (correctly_generated_information_steps_count/generated_information_steps_count) + "
            "correctly_generated_command_steps_count/generated_command_steps_count)."
            "Range: [0,1]."
        ),
    )

    total_generated_steps_require_iteration: int = Field(
        default=0,
        description="Total number of generated steps that require iteration/loops",
    )

    correctly_generated_iterative_steps: int = Field(
        default=0, description="Number of iterative steps correctly generated."
    )

    iteration_handling_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Iteration handling accuracy. "
            "Computed as correctly_generated_iterative_steps / total_generated_steps_require_iteration. "
            "Range: [0,1]."
        ),
    )

    num_redundant_steps: int = Field(
        default=0,
        description="Number of generated steps that are redundant and do not contribute to fulfilling the user's request.",
    )

    redundancy_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Redundancy score. "
            "Computed as 1 - (num_redundant_steps / generated_steps_count). "
            "Range: [0,1]."
        ),
    )


class UserValidationEvaluation(BaseModel):
    """
    Evaluation result for the User Validation node.
    Evaluates the quality of the plan representation shown to the user.
    """

    evaluation_needed: bool = Field(
        default=True,
        description="Ground truth indicating whether user validation evaluation was needed.",
    )

    evaluation_score: float = Field(
        default=0.0,
        ge=0.0,
        le=10.0,
        description=(
            "Overall evaluation score for the plan presentation quality. "
            "Range: [0,10]. "
            "Higher scores indicate clearer, more accurate, safer, and more user-friendly plan representation."
        ),
    )

    evaluation_reasoning: str = Field(
        default="",
        description=(
            "Detailed reasoning explaining why the score was assigned. "
            "Should include strengths, weaknesses, clarity issues, safety communication quality, "
            "and overall user experience evaluation."
        ),
    )


class StepResolverEvaluation(BaseModel):
    """
    Evaluation metrics for the Step Resolver node
    for a SINGLE evaluation data point.
    """

    evaluation_needed: bool = Field(
        default=True,
        description="Ground truth indicating whether step resolution evaluation was needed.",
    )

    expected_resolution_success: bool = Field(
        default=False, description="Expected feasibility/resolution outcome."
    )

    generated_resolution_success: bool = Field(
        default=False,
        description="Actual feasibility/resolution decision produced by the resolver.",
    )

    total_generated_placeholders: int = Field(
        default=0,
        description="Total number of generated placeholders that needed resolution.",
    )

    correctly_resolved_placeholders: int = Field(
        default=0, description="Number of placeholders resolved correctly."
    )

    placeholder_resolution_accuracy: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Placeholder resolution accuracy. "
            "Computed as correctly_resolved_placeholders / total_generated_placeholders. "
            "Range: [0,1]."
        ),
    )

    expected_generated_resolved_steps_count: int = Field(
        default=0, description="Expected number of generated and resolved steps."
    )

    actual_generated_resolved_steps_count: int = Field(
        default=0, description="Actual number of resolved/generated steps."
    )

    is_iteration_expansion_correct: bool = Field(
        default=False,
        description=(
            "True if the number of generated iterative steps "
            "matches the expected number."
        ),
    )


